"""The sound library: effects, ambience beds and music, each with its
licence and the credit the description needs.

Three sources, all checked:

* **Generated here** (``sound_synth``): whooshes, risers, booms, impacts,
  ticks, drones and ambience beds. No third party has rights in them.
* **Kenney audio packs**, CC0 ("Creative Commons CC0" on each pack page
  and in the pack's License.txt). Used for extra impacts and interface
  ticks. No credit is required; one is given anyway.
* **Kevin MacLeod, incompetech.com**, CC BY 4.0. The FAQ says YouTube use
  is allowed and may be monetised, with this credit:
  ``"Title" Kevin MacLeod (incompetech.com) Licensed under Creative
  Commons: By Attribution 4.0 http://creativecommons.org/licenses/by/4.0/``.
  Tracks are chosen by the "feel" tags in incompetech's own catalogue and
  downloaded one at a time, when a film needs them, never in bulk.

Every entry goes through ``stock_media.classify_licence``, the same gate
pictures go through, so a share-alike or non-commercial file cannot get in.
"""

from __future__ import annotations

import json
import logging
import random
import subprocess
import urllib.parse
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import httpx

from app.config import get_settings
from app.services import sound_synth

log = logging.getLogger(__name__)

INCOMPETECH_CATALOGUE = "https://incompetech.com/music/royalty-free/pieces.json"
INCOMPETECH_FILE = "https://incompetech.com/music/royalty-free/mp3-royaltyfree/{name}"
INCOMPETECH_CREDIT = (
    '"{title}" Kevin MacLeod (incompetech.com) Licensed under Creative Commons: '
    "By Attribution 4.0 http://creativecommons.org/licenses/by/4.0/"
)
USER_AGENT = "AIVideoManager/0.1 (local desktop video tool)"

#: incompetech "feel" tags that fit each mood, best first, and the tags
#: that rule a track out for it.
MOOD_FEELS: dict[str, tuple[tuple[str, ...], tuple[str, ...]]] = {
    "tense": (("Suspenseful", "Unnerving", "Intense", "Mysterious"), ("Humorous", "Bouncy", "Grooving", "Bright")),
    "steady": (("Mysterious", "Somber", "Calming", "Driving"), ("Humorous", "Bouncy", "Grooving", "Aggressive")),
    "epic": (("Epic", "Intense", "Action"), ("Humorous", "Bouncy", "Relaxed")),
    "driving": (("Driving", "Action", "Intense"), ("Humorous", "Bouncy", "Relaxed", "Calming")),
    "reflective": (("Somber", "Calming", "Uplifting"), ("Humorous", "Bouncy", "Aggressive", "Action")),
    "dark": (("Dark", "Eerie", "Unnerving"), ("Humorous", "Bouncy", "Bright", "Uplifting")),
    "hopeful": (("Uplifting", "Bright", "Calming"), ("Humorous", "Bouncy", "Dark", "Eerie")),
}
#: Genres and instruments that read as a game or a cartoon under narration.
_UNSUITABLE = (
    "ren faire", "medieval", "polka", "kazoo", "banjo", "chiptune", "8-bit", "comedy",
    "carnival", "circus", "christmas", "holiday", "children", "cartoon", "silly", "vocals",
)
MIN_TRACK_S = 120


@dataclass
class Sound:
    path: str
    kind: str  # "sfx", "ambience" or "music"
    tag: str
    licence: str
    source: str
    credit: str
    duration_s: float = 0.0
    title: str = ""


def root() -> Path:
    return get_settings().data_root / "sfx"


def music_root() -> Path:
    return get_settings().data_root / "music" / "incompetech"


def index_path() -> Path:
    return root() / "index.json"


def load_index() -> list[Sound]:
    path = index_path()
    if not path.exists():
        return []
    return [Sound(**row) for row in json.loads(path.read_text(encoding="utf-8"))]


def save_index(entries: list[Sound]) -> None:
    index_path().parent.mkdir(parents=True, exist_ok=True)
    index_path().write_text(json.dumps([asdict(e) for e in entries], indent=1), encoding="utf-8")


def _allowed(licence: str) -> bool:
    from app.services.stock_media import classify_licence

    return classify_licence(licence).allowed


# ---------------------------------------------------------------------------
# Building the library
# ---------------------------------------------------------------------------

#: Variants generated per cue, so a film with many whooshes does not
#: repeat the same one.
VARIANTS = 4


def build_generated(force: bool = False) -> list[Sound]:
    """Generate the cue and ambience files that are made on this machine."""
    entries: list[Sound] = []
    folder = root() / "generated"
    for tag, maker in sound_synth.CUES.items():
        for seed in range(VARIANTS):
            path = folder / f"{tag}-{seed}.wav"
            if force or not path.exists():
                sound_synth.write_wav(maker(seed), path)
            entries.append(Sound(str(path), "sfx", tag, "Public domain (generated by this tool)",
                                 "Generated by AI Video Generation Manager", ""))
    for tag in sound_synth.AMBIENCE_TAGS:
        for seed in range(2):
            path = folder / f"amb-{tag}-{seed}.wav"
            if force or not path.exists():
                sound_synth.write_wav(sound_synth.ambience(tag, seed), path)
            entries.append(Sound(str(path), "ambience", tag, "Public domain (generated by this tool)",
                                 "Generated by AI Video Generation Manager", ""))
    return entries


#: Kenney files worth using, by tag. Matched on the start of the filename.
#: The impact packs are short game hits and read as thin under a film,
#: so only the interface ticks are used; the impacts are generated.
KENNEY_PICKS: dict[str, tuple[str, ...]] = {
    "tick": ("tick_",),
}


def scan_kenney() -> list[Sound]:
    entries: list[Sound] = []
    base = root() / "kenney"
    if not base.exists():
        return entries
    for pack in base.iterdir():
        if not pack.is_dir():
            continue
        licence_file = next(pack.rglob("License*.txt"), None)
        licence_text = licence_file.read_text(encoding="utf-8", errors="ignore") if licence_file else ""
        if "CC0" not in licence_text and "Creative Commons Zero" not in licence_text:
            log.warning("Kenney pack %s has no CC0 licence file; skipped.", pack.name)
            continue
        for path in pack.rglob("*.ogg"):
            for tag, prefixes in KENNEY_PICKS.items():
                if path.stem.startswith(prefixes):
                    entries.append(Sound(str(path), "sfx", tag, "CC0",
                                         f"Kenney ({pack.name}), kenney.nl",
                                         "Sound effects: Kenney (kenney.nl), CC0"))
    return entries


def rebuild(force: bool = False) -> list[Sound]:
    """Regenerate and rescan everything, keeping music already downloaded."""
    music = [e for e in load_index() if e.kind == "music" and Path(e.path).exists()]
    entries = [e for e in build_generated(force) + scan_kenney() + music if _allowed(e.licence)]
    save_index(entries)
    return entries


# ---------------------------------------------------------------------------
# Choosing
# ---------------------------------------------------------------------------


def pick(kind: str, tag: str, *, seed: int = 0, entries: list[Sound] | None = None) -> Sound | None:
    """One sound for a tag, varied by ``seed`` so repeats are not identical.

    Generated sounds come first for cinematic cues; Kenney files are added
    to the pool for impacts and ticks.
    """
    pool = [e for e in (entries if entries is not None else load_index())
            if e.kind == kind and e.tag == tag and Path(e.path).exists()]
    if not pool:
        return None
    return pool[seed % len(pool)]


def _catalogue() -> list[dict[str, Any]]:
    cache = music_root() / "pieces.json"
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        response = httpx.get(INCOMPETECH_CATALOGUE, headers={"User-Agent": USER_AGENT}, timeout=60)
        response.raise_for_status()
        cache.write_bytes(response.content)
    return json.loads(cache.read_text(encoding="utf-8"))


def _seconds(length: str) -> int:
    parts = [int(p) for p in str(length or "0").split(":") if p.isdigit()]
    total = 0
    for part in parts:
        total = total * 60 + part
    return total


def candidates(mood: str) -> list[dict[str, Any]]:
    """incompetech tracks for a mood, best fit first."""
    wanted, refused = MOOD_FEELS.get(mood, MOOD_FEELS["steady"])
    scored = []
    for piece in _catalogue():
        feels = [f.strip() for f in str(piece.get("feel") or "").split(",") if f.strip()]
        text = " ".join(str(piece.get(k) or "") for k in ("instruments", "description", "feel")).lower()
        if any(f in refused for f in feels) or any(word in text for word in _UNSUITABLE):
            continue
        if _seconds(piece.get("length")) < MIN_TRACK_S:
            continue
        score = sum(len(wanted) - wanted.index(f) for f in feels if f in wanted)
        if score:
            scored.append((score, piece["title"], piece))
    scored.sort(key=lambda item: (-item[0], item[1]))
    return [item[2] for item in scored]


def music_for(mood: str, *, avoid: set[str] | None = None, seed: int = 0) -> Sound | None:
    """A track for this mood, downloaded the first time it is needed."""
    avoid = avoid or set()
    entries = load_index()
    local = [e for e in entries if e.kind == "music" and e.tag == mood
             and e.path not in avoid and Path(e.path).exists()]
    pool = candidates(mood)[:12]
    if not pool and not local:
        return None
    rng = random.Random(f"{mood}-{seed}")
    rng.shuffle(pool)
    for piece in pool:
        destination = music_root() / piece["filename"]
        if str(destination) in avoid:
            continue
        if not destination.exists():
            url = INCOMPETECH_FILE.format(name=urllib.parse.quote(piece["filename"]))
            try:
                with httpx.stream("GET", url, headers={"User-Agent": USER_AGENT},
                                  timeout=120, follow_redirects=True) as response:
                    response.raise_for_status()
                    partial = destination.with_suffix(".part")
                    with partial.open("wb") as handle:
                        for chunk in response.iter_bytes():
                            handle.write(chunk)
                partial.replace(destination)
            except httpx.HTTPError as exc:
                log.warning("Could not fetch %s: %s", url, exc)
                continue
            (destination.with_name(destination.stem + "-license.txt")).write_text(
                INCOMPETECH_CREDIT.format(title=piece["title"]) + "\n"
                f"Source: {url}\nFeel: {piece.get('feel')}\n",
                encoding="utf-8",
            )
        entry = Sound(
            str(destination), "music", mood, "CC BY 4.0", "Kevin MacLeod, incompetech.com",
            INCOMPETECH_CREDIT.format(title=piece["title"]),
            float(_seconds(piece.get("length"))), piece["title"],
        )
        entries = [e for e in entries if e.path != entry.path] + [entry]
        save_index(entries)
        return entry
    return local[0] if local else None


def duration(ffprobe_path: str, path: Path) -> float:
    out = subprocess.run(
        [ffprobe_path, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True,
    ).stdout.strip()
    try:
        return float(out)
    except ValueError:
        return 0.0
