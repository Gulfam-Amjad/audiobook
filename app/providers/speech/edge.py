"""Narration through Microsoft's online neural voices, via the ``edge-tts`` package.

Not open source and not offline. The voice is generated by Microsoft's
service, so this needs an internet connection, and ``edge-tts`` talks to that
service through an interface Microsoft has not published. Its terms have not
been checked here, so commercial use of these voices is reported as unknown.

Speed follows the same convention as the other engines: ``length_scale`` is
the inverse of speed, converted to the percentage ``edge-tts`` expects. The
service returns MP3, which ffmpeg converts to the 24 kHz mono WAV the rest of
the pipeline measures.
"""

from __future__ import annotations

import asyncio
import json
import logging
from pathlib import Path

from app.constants import ErrorClass
from app.providers.speech.base import (
    SpeechCapabilities,
    SpeechProvider,
    SpeechProviderError,
    SpeechResult,
    VoiceSettings,
)
from app.services import ffmpeg

log = logging.getLogger(__name__)

ENGINE_VERSION = "edge-tts"
SAMPLE_RATE = 24_000
#: Edge's rate control accepts roughly this span; anything beyond it is refused.
MIN_RATE_PCT, MAX_RATE_PCT = -50, 100
#: One sentence is seconds of audio. Longer than this means the service hung.
SYNTH_TIMEOUT_S = 120
MIN_WAV_BYTES = 1024
#: Edge reports word offsets in 100-nanosecond ticks.
TICKS_PER_S = 10_000_000

#: Voices worth offering for Hindi and Urdu, as the service names them.
VOICES = (
    "hi-IN-MadhurNeural",
    "hi-IN-SwaraNeural",
    "ur-PK-AsadNeural",
    "ur-PK-UzmaNeural",
    "ur-IN-SalmanNeural",
    "ur-IN-GulNeural",
)


def rate_for(length_scale: float) -> str:
    """Convert a length scale to an edge-tts rate string such as ``+10%``."""
    speed = 1.0 / length_scale if length_scale > 0 else 1.0
    percent = round((speed - 1.0) * 100)
    percent = min(max(percent, MIN_RATE_PCT), MAX_RATE_PCT)
    return f"{percent:+d}%"


def language_for(voice_name: str) -> str:
    """``hi-IN-SwaraNeural`` -> ``hi_IN``, the form the voice table uses."""
    parts = voice_name.split("-")
    return f"{parts[0]}_{parts[1]}" if len(parts) >= 2 else ""


class EdgeSpeechProvider(SpeechProvider):
    key = "edge"

    def capabilities(self) -> SpeechCapabilities:
        return SpeechCapabilities(
            key=self.key,
            display_name="Microsoft neural voices (edge-tts)",
            local=False,
            output_format="mp3",
            automated=True,
            docs_url="https://github.com/rany2/edge-tts",
            licence="Microsoft service terms; edge-tts is LGPL-3.0",
            licence_note=(
                "The voices are generated by Microsoft's online service, not on this "
                "machine. Their terms were not checked here, so commercial use is unknown."
            ),
            checked_on="2026-11-10",
            invocation_verified=True,
            notes=(
                "Needs an internet connection. Free to use, with no key.",
                "Uses an unofficial interface to the service, so it can break without notice.",
            ),
        )

    async def is_available(self) -> tuple[bool, str]:
        try:
            import edge_tts  # noqa: F401
        except ImportError as exc:
            return False, f"edge-tts is not installed ({exc})."
        status = await ffmpeg.detect()
        if not status.ffmpeg_path:
            return False, "ffmpeg is needed to convert Edge's output to WAV, and was not found."
        return True, "Microsoft's neural voices are available."

    async def synthesise(self, text: str, voice: VoiceSettings, destination: Path) -> SpeechResult:
        line = " ".join((text or "").split())
        if not line:
            raise SpeechProviderError("There is nothing to say: the line is empty.", ErrorClass.INVALID_INPUT)
        if not voice.voice_key:
            raise SpeechProviderError("No Edge voice is named on this profile.", ErrorClass.INVALID_INPUT)

        status = await ffmpeg.detect()
        if not status.ffmpeg_path:
            raise SpeechProviderError(
                "ffmpeg was not found, so Edge's MP3 cannot be converted to WAV.",
                ErrorClass.INVALID_INPUT,
            )

        destination.parent.mkdir(parents=True, exist_ok=True)
        mp3 = destination.with_name(destination.stem + ".edge.mp3")
        partial = destination.with_suffix(destination.suffix + ".part")
        mp3.unlink(missing_ok=True)
        partial.unlink(missing_ok=True)

        words: list[list] = []
        try:
            import edge_tts

            communicate = edge_tts.Communicate(
                line, voice.voice_key, rate=rate_for(voice.length_scale), boundary="WordBoundary"
            )
            await asyncio.wait_for(self._stream(communicate, mp3, words), timeout=SYNTH_TIMEOUT_S)
        except TimeoutError:
            mp3.unlink(missing_ok=True)
            raise SpeechProviderError(
                f"Edge did not answer within {SYNTH_TIMEOUT_S}s.", ErrorClass.TRANSIENT
            ) from None
        except Exception as exc:  # noqa: BLE001 - edge-tts raises several network error types
            mp3.unlink(missing_ok=True)
            raise SpeechProviderError(
                f"Edge's voice service failed: {type(exc).__name__}: {exc}", ErrorClass.TRANSIENT
            ) from exc

        if not mp3.exists() or mp3.stat().st_size == 0:
            mp3.unlink(missing_ok=True)
            raise SpeechProviderError("Edge returned no audio.", ErrorClass.TRANSIENT)

        await self._to_wav(status.ffmpeg_path, mp3, partial, voice.sentence_silence_s)
        mp3.unlink(missing_ok=True)

        size = partial.stat().st_size if partial.exists() else 0
        if size < MIN_WAV_BYTES:
            partial.unlink(missing_ok=True)
            raise SpeechProviderError(f"Converting Edge's audio left only {size} bytes.", ErrorClass.UNKNOWN)
        sidecar = destination.with_suffix(".words.json")
        if words:
            sidecar.write_text(json.dumps(words, ensure_ascii=False), encoding="utf-8")
        else:
            sidecar.unlink(missing_ok=True)
        destination.unlink(missing_ok=True)
        partial.replace(destination)
        return SpeechResult(
            path=destination,
            sample_rate=SAMPLE_RATE,
            size_bytes=size,
            engine_version=ENGINE_VERSION,
        )

    @staticmethod
    async def _stream(communicate, mp3: Path, words: list[list]) -> None:
        """Save the audio and collect each word's start and end, in seconds."""
        with mp3.open("wb") as handle:
            async for chunk in communicate.stream():
                kind = chunk.get("type")
                if kind == "audio":
                    handle.write(chunk["data"])
                elif kind == "WordBoundary":
                    start = chunk["offset"] / TICKS_PER_S
                    words.append([chunk["text"], round(start, 3),
                                  round(start + chunk["duration"] / TICKS_PER_S, 3)])

    async def _to_wav(self, ffmpeg_path: str, source: Path, destination: Path, silence_s: float) -> None:
        pad = max(silence_s, 0.0)
        args = [
            ffmpeg_path, "-y", "-loglevel", "error",
            "-i", str(source),
            "-af", f"apad=pad_dur={pad:.3f}",
            "-ac", "1", "-ar", str(SAMPLE_RATE),
            "-c:a", "pcm_s16le", "-f", "wav", str(destination),
        ]
        process = await asyncio.create_subprocess_exec(
            *args,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        _, stderr = await process.communicate()
        if process.returncode:
            destination.unlink(missing_ok=True)
            detail = stderr.decode("utf-8", "replace").strip()[:300]
            raise SpeechProviderError(
                f"ffmpeg could not convert Edge's audio. {detail}", ErrorClass.UNKNOWN
            )
